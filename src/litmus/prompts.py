# v0.4.0 起：在对话开头追加一句格式提醒（turn-reminder）。
# 实测理由：glm-4-flash 会忽略 system prompt 里的格式要求——跑 demo 库时既没输出
# plan:，最终答案也没加 answer: 前缀（第 2 步就把结论当答案交了）。只在 system
# 里写一次不够，要在消息序列里也出现一次。做法借自 Claude Code 的 output-styles：
# 把最容易被违反的那条规则压成一句话，靠近调用点再提醒一次。
TURN_REMINDER: dict[str, str] = {
    "v0.4.0": (
        "格式提醒：动手前先单独输出一行 `plan: ...`（不调用工具）；"
        "最终回答必须以 `answer:` 或 `unverified:` 或 `failed:` 开头。"
        "没有这三个前缀之一的输出不算结束。"
    ),
}

SYSTEM_PROMPTS: dict[str, str] = {
    "v0.2.0": _RULES_V2,
    "v0.3.0": _RULES_V3,
    # v0.3.1 只改一条：v0.3.0 的"先写下取数计划"让模型把计划当答案交付
    # （实测 q20/q28 只跑 1 步就输出计划），所以改成"在心里想，不要写出来"。
    "v0.3.1": _RULES_V31,
    # v0.4.0（2026-10-26）：状态显式化 + 计划有物理落点。
    # 来由：v0.3.1 的"在心里想"依赖模型自觉，最终答案仍是自由文本，
    # 失败 / 未核实这两种情况机器分不出来。改成三态前缀，plan 行由 loop 剥离记录。
    # 参考 Claude Code 的 result:/needs input:/failed: 与 plan-mode 的"计划独立落点"。
    "v0.4.0": _RULES_V4,
}

# loop 里检测到连续重复调用后注入的强制反思指令（v0.3.0 起启用）
FORCE_REFLECT = """你已经连续 {n} 次重复同一个操作，这不会带来新信息。

现在停下来，先回答两个问题（各一句话）：
1. 你认为卡住的根本原因是什么（列不属于这张表？口径不对？数据里没有你假设的取值？）
2. 你接下来要走哪条**还没试过**的路径？

然后按新路径继续。不要再提交与之前相同或只改一个字的查询。"""


def system_prompt(version: str) -> str:
    if version not in SYSTEM_PROMPTS:
        raise KeyError(
            f"未知提示词版本 {version}，可用版本：{', '.join(SYSTEM_PROMPTS)}"
        )
    return SYSTEM_PROMPTS[version]
